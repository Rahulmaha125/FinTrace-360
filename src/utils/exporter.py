"""
FinTrace 360 - Report Generation & Export Module
Exports cleaned financial records, anomaly triage logs, and executive markdown summaries.
"""

import io
from typing import Any
import pandas as pd

def export_dataframe_to_csv(df: pd.DataFrame) -> bytes:
    """Exports DataFrame to UTF-8 encoded CSV bytes."""
    return df.to_csv(index=False).encode("utf-8")

def export_dataframe_to_excel(df: pd.DataFrame) -> bytes | None:
    """Exports DataFrame to Excel bytes if openpyxl is installed; otherwise returns None."""
    try:
        output = io.BytesIO()
        with pd.ExcelWriter(output, engine="openpyxl") as writer:
            df.to_excel(writer, index=False, sheet_name="Transactions")
        return output.getvalue()
    except Exception:
        return None

